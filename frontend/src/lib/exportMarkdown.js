import { sanitizeReport } from "./sanitize";
import { SEVERITIES, SEVERITY_LABEL } from "./severity";

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

function location(f) {
  if (f.type === "dependency") return `${f.package?.name}@${f.package?.version}${f.file ? ` (${f.file})` : ""}`;
  return `${f.file}${f.line ? `:${f.line}` : ""}`;
}

/** Markdown version of a report. Secrets are always masked. */
export function reportToMarkdown(raw) {
  const r = sanitizeReport(raw);
  const out = [];
  const counts = r.severityCounts || {};
  out.push(`# CipherGuard report: ${r.target?.slug || r.repository}`);
  out.push("");
  out.push(`- Repository: ${r.repository}`);
  out.push(`- Scanned: ${r.scanTimestamp}`);
  if (r.risk) out.push(`- Risk score: **${r.risk.score}/100 (grade ${r.risk.grade})**`);
  out.push(`- Findings: ${SEVERITIES.map((s) => `${counts[s] || 0} ${s}`).join(", ")}`);
  out.push(`- Files scanned: ${r.totalFilesScanned ?? "–"}; dependencies checked: ${r.dependenciesScanned ?? "–"}`);
  const sc = r.posture?.scorecard;
  if (sc) out.push(`- OpenSSF Scorecard: ${sc.score}/10 (${sc.url})`);
  out.push("");

  if (r.overallAssessment) {
    out.push("## Summary", "", r.overallAssessment.trim(), "");
  }

  for (const sev of SEVERITIES) {
    const items = r.findings.filter((f) => f.severity === sev);
    if (!items.length) continue;
    out.push(`## ${SEVERITY_LABEL[sev]} (${items.length})`, "");
    for (const f of items) {
      const a = f.advisory;
      const tags = [a?.kev && "**Known exploited (CISA KEV)**", a?.epss && `EPSS ${(a.epss.score * 100).toFixed(1)}%`, a?.cvss?.score != null && `CVSS ${a.cvss.score}`]
        .filter(Boolean)
        .join(" · ");
      out.push(`### ${esc(f.title)}`);
      out.push("");
      out.push(`- Rule: \`${f.rule}\`  `);
      out.push(`- Location: \`${location(f)}\`  `);
      if (tags) out.push(`- ${tags}  `);
      if (f.package?.fixedVersion) out.push(`- Fixed in: ${f.package.fixedVersion}  `);
      if (f.match && f.type !== "dependency") out.push(`- Match: \`${esc(f.match)}\`  `);
      if (f.ai?.explanation) out.push("", f.ai.explanation);
      out.push("", `**Fix:** ${f.ai?.fix || f.remediation || "Review manually."}`);
      const links = (f.sources || []).filter((s) => s.url).map((s) => `[${s.name}](${s.url})`);
      if (links.length) out.push("", `Sources: ${links.join(", ")}`);
      out.push("");
    }
  }

  if (r.sources?.length) {
    out.push("## Data sources", "", "| Source | Status | Detail |", "|---|---|---|");
    for (const s of r.sources) out.push(`| [${s.name}](${s.url}) | ${s.status} | ${esc(s.detail)} |`);
    out.push("");
  }
  out.push("_Generated by CipherGuard. Secret values are masked._", "");
  return out.join("\n");
}

export function download(filename, text, type = "text/markdown") {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
